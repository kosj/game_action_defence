import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(process.env.RIG_NODE_MODULES+'/package.json');
const {chromium}=require('playwright');
const b=await chromium.launch({headless:true,channel:'chrome'});
const page=await b.newPage();const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:8765');await page.waitForFunction(()=>window.rig?.ready);
await page.locator('#pause').click();assert.equal(await page.locator('#pause').innerText(),'재생');
await page.locator('#direction').selectOption('E');
await page.locator('#bones').check();
await page.locator('#scrub').fill('50');
await page.waitForFunction(()=>document.querySelector('#phase').textContent==='50%');
const a=await page.locator('canvas').screenshot();
await page.locator('#scrub').fill('0');
await page.waitForFunction(()=>document.querySelector('#phase').textContent==='0%');
const c=await page.locator('canvas').screenshot();assert(!a.equals(c));
await page.locator('#direction').selectOption('all');await page.locator('#bones').uncheck();
await page.locator('#speed').fill('0.5');await page.locator('#pause').click();
await page.waitForFunction(()=>document.querySelector('#phase').textContent!=='0%');
assert.equal(errors.length,0,errors.join('\n'));await b.close();
console.log('PASS: pause/resume, 8-direction/single direction, bones, phase scrub, speed, no browser errors');
